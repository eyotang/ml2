export default function AnswerNote({ note, summary }) {
  if (!note && !summary) return null;
  return (
    <section className="answer-note" aria-label="答案说明">
      <h4>答案说明</h4>
      {summary ? (
        <p>{summary}</p>
      ) : (
        note.map((text, i) => (
          <p key={i}>
            <strong>{["理解重点：", "答题思路：", "易错提醒："][i]}</strong>
            {text}
          </p>
        ))
      )}
    </section>
  );
}
